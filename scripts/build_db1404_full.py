def classify_category(name: str) -> tuple[str, str, bool]:
    """Return the most specific category: longer keywords win over short ones."""
    best: tuple[int, str, str] | None = None
    for keyword, l1, l2 in CATEGORY_RULES:
        if keyword in name and (best is None or len(keyword) > best[0]):
            best = (len(keyword), l1, l2)
    if best is None:
        return "其他", "待分类", False
    return best[1], best[2], True


def split_alternatives(raw: str) -> list[str]:
    """Collect alias candidates printed before the first explanatory marker."""
    head = raw
    for marker in ("（", "(", "【", "[", "，", ",", "。", "；", ";"):
        position = head.find(marker)
        if position > 0:
            head = head[:position]
    parts = [part.strip("】]“”‘’\"' ") for part in re.split(r"[、,，/]", head)]
    return [part for part in parts if part]


def build_aliases(entry: dict) -> list[str]:
    aliases: list[str] = []
    cleaned = entry["cleaned"]
    for part in split_alternatives(entry["raw"]):
        if part and part != cleaned and 1 <= len(part) <= 12 and part not in aliases:
            aliases.append(part)
    for reference in entry.get("cross_refs", []):
        text = reference["text"]
        text = re.sub(r"^(也是|同上|同)", "", text).strip()
        if text and text != cleaned and len(text) <= 12 and text not in aliases:
            aliases.append(text)
    return aliases[:5]


